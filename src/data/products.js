export const categoryBySlug = (slug) =>
  categories.find((category) => category.slug === slug);

export const occasionBySlug = (slug) =>
  occasions.find((occasion) => occasion.slug === slug);

export const findProduct = (idOrSlug) =>
  products.find((product) => product.id === idOrSlug || product.slug === idOrSlug);

export const getRelatedProducts = (product, limit = 4) =>
  products
    .filter(
      (candidate) =>
        candidate.id !== product.id &&
        (candidate.categorySlug === product.categorySlug ||
          candidate.occasion.some((occasion) => product.occasion.includes(occasion)))
    )
    .slice(0, limit);

export const formatPrice = (value) =>
  new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(value);
